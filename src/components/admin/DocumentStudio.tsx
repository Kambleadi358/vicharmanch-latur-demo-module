const DOC_META: Record<DocType, { label: string; icon: any; color: string; desc: string }> = {
  invitation:     { label: "निमंत्रण पत्र",   icon: Mail,        color: "from-blue-500 to-indigo-600",   desc: "अधिकृत निमंत्रण पत्र तयार करा" },
  permission:     { label: "परवानगी पत्र",   icon: ShieldCheck, color: "from-emerald-500 to-teal-600",  desc: "अधिकाऱ्यांना अर्ज / परवानगी पत्र" },
  schedule:       { label: "कार्यक्रम पत्रिका", icon: CalendarDays, color: "from-amber-500 to-orange-600", desc: "रंगीत कार्यक्रम पत्रिका बनवा" },
  congratulation: { label: "अभिनंदन पत्र",   icon: Award,       color: "from-pink-500 to-rose-600",     desc: "मानपत्र / अभिनंदन पत्र" },
  press:          { label: "प्रसिद्धीपत्रक",  icon: Newspaper,   color: "from-slate-600 to-slate-800",  desc: "प्रेस नोट / प्रसिद्धीपत्रक" },
};

function esc(s: any) {
  return String(s ?? "").replace(/[&<>"']/g, (c) => ({ "&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#39;" }[c]!));
}

